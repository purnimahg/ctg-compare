#!/usr/bin/env python3
"""
ctg-compare - resume check

Run this FIRST at the start of every session. It answers one question:
has the registry changed since you last saved a copy?

A saved file is a snapshot, not a subscription. Sponsors amend registered
trials whenever they like. If you build on a stale copy you will produce a
report that is internally consistent, fully traceable, and wrong.

Run:  python3 resume-check.py

Exit codes:  0 = all current   1 = could not check   2 = something is stale
"""

import hashlib
import json
import re
import sys
import urllib.request
import urllib.error
from pathlib import Path

BASE = "https://clinicaltrials.gov/api/v2/studies"
HERE = Path(__file__).resolve().parent
DATA = HERE / "data"
FNAME = re.compile(r"^(NCT\d+)_(\d{4}-\d{2}-\d{2})\.json$")


def newest_local():
    """Latest saved snapshot per trial -> {nct: (fetched_on, last_update_in_file, path)}"""
    out = {}
    for f in sorted(DATA.glob("*.json")):
        m = FNAME.match(f.name)
        if not m:
            continue
        nct, fetched = m.group(1), m.group(2)
        if nct in out and out[nct][0] >= fetched:
            continue
        rec = json.loads(f.read_text())
        upd = rec["protocolSection"]["statusModule"]["lastUpdatePostDateStruct"]["date"]
        out[nct] = (fetched, upd, f, protocol_fingerprint(rec))
    return out


def protocol_fingerprint(record):
    """Short hash of protocolSection only.

    Why not the whole record: derivedSection is regenerated by the registry
    (MeSH terms and similar) and churns constantly, which would cry wolf.
    Why not lastUpdatePostDate alone: that date only moves when the SPONSOR
    submits a change. The registry also edits protocolSection by itself -
    auto-linking a PubMed citation, for instance - without touching it.
    See KNOWN-LIMITATIONS.md, L1.
    """
    blob = json.dumps(record["protocolSection"], sort_keys=True).encode()
    return hashlib.sha256(blob).hexdigest()[:12]


def live_state(nct_ids):
    """Full records, so we can fingerprint them. Returns {nct: (date, fingerprint)}."""
    out = {}
    for nct in nct_ids:
        url = f"{BASE}/{nct}?format=json"
        with urllib.request.urlopen(url, timeout=30) as r:
            rec = json.load(r)
        out[nct] = (
            rec["protocolSection"]["statusModule"]["lastUpdatePostDateStruct"]["date"],
            protocol_fingerprint(rec),
        )
    return out


def main():
    if not DATA.exists() or not list(DATA.glob("*.json")):
        print("No saved snapshots in data/.")
        print("Run:  python3 fetch.py")
        sys.exit(1)

    local = newest_local()
    print(f"Newest saved snapshot for each of {len(local)} trial(s):\n")

    try:
        live = live_state(sorted(local))
    except urllib.error.URLError as e:
        print(f"  Could not reach clinicaltrials.gov ({e.reason}).")
        print("  Cannot tell whether your copies are current. Stopping.")
        sys.exit(1)

    stale = []
    pad = " " * 13
    for nct in sorted(local):
        fetched, saved_upd, path, saved_fp = local[nct]
        if nct not in live:
            print(f"  {nct}   ?         the registry did not return this trial")
            continue
        now_upd, now_fp = live[nct]
        date_same = (now_upd == saved_upd)
        content_same = (now_fp == saved_fp)

        if date_same and content_same:
            print(f"  {nct}   CURRENT")
            print(f"{pad}sponsor last edited {saved_upd}; content unchanged "
                  f"(you fetched {fetched})")
            continue

        stale.append(nct)
        print(f"  {nct}   STALE     your copy: {path.name} (fetched {fetched})")
        if not date_same:
            print(f"{pad}SPONSOR EDIT  your copy says {saved_upd}, registry says {now_upd}")
        else:
            print(f"{pad}sponsor edit date unchanged ({saved_upd})")
        if not content_same:
            print(f"{pad}CONTENT       protocolSection differs "
                  f"({saved_fp} -> {now_fp})")
            if date_same:
                print(f"{pad}              changed WITHOUT a sponsor edit - this is a"
                      f" registry-side edit. See KNOWN-LIMITATIONS.md L1.")

    print()
    if stale:
        print(f"{len(stale)} record(s) have changed since you last fetched.")
        print("Run  python3 fetch.py  to save today's snapshot ALONGSIDE the old one.")
        print("Nothing is overwritten. The date in the filename keeps both.")
        sys.exit(2)

    print("All saved copies are current. Safe to carry on.")


if __name__ == "__main__":
    main()
